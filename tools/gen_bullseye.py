"""Insert the BullsEye screen tour into projects/cooling.html (between tour markers).
The tour is scroll driven and fully scrubbed: the whole block (steps, screen, text)
pins to the viewport, and scrolling moves a cursor across the screen; when it clicks,
the screen changes as it does in the product. No zoom, no autoplay.
Usage: python3 tools/gen_bullseye.py <portfolio_root> [--images]
  --images  also rebuild the flat screens (f-*.webp) from the layered exports (needs Pillow)"""
import html, json, re, sys
ROOT = sys.argv[1]; e = html.escape
W, H, FOLDER = 1280, 832, 'work/cooling/tour'

# Flat screens, in the order they appear. (file, alt, layers to flatten: (file, x, y) in screen px)
tiles = [(98, 273), (384.3, 273), (670.5, 273), (956.8, 273), (98, 467), (384.3, 467), (670.5, 467), (956.8, 467), (98, 661), (384.3, 661), (670.5, 661)]
SHOTS = [
 ('f-overview', 'Camera overview: the state of each cooling group and a tile for every camera',
  [('s1-base', 0, 0)] + [(f's1-card{i+1}', x, 124) for i, x in enumerate([110, 497.3, 884.7])] + [(f's1-cam{i+1}', x, y) for i, (x, y) in enumerate(tiles)]),
 ('f-live', 'A single camera: the image of the feed lane with a region for every feeding spot',
  [('s2-base', 0, 0), ('s2-top', 102, 165), ('s2-bottom', 98, 520)]),
 ('f-fan', 'The same camera with one fan selected and the spots it covers highlighted', [('s2-fan', 0, 0)]),
 ('f-basic', 'Group schedule in basic settings', [('s3-basic', 0, 0)]),
 ('f-advanced', 'Group schedule with advanced settings switched on', [('s3-adv', 0, 0)]),
]
# Steps: (name, text). The text beside the screen; one is visible at a time.
STEPS = [
 ('Check', 'Every camera and every cooling group on one screen. A camera that is down stands out at once.'),
 ('Open a camera', 'The live image comes first, and every feeding spot is a region on it.'),
 ('Check a fan', 'Pick a fan to see exactly which spots it covers.'),
 ('Adjust', 'Basic settings hold the times that change from day to day. Everything else is one toggle away.'),
]
# Timeline, played by scrolling. Lengths are in screens of scroll (x UNIT).
#   ('hold', len)          nothing moves; time to read
#   ('move', x, y, len)    the cursor travels to x,y (screen px)
#   ('click', shot)        click pulse, then that shot shows
#   ('show', shot)         that shot shows without a click (hover states)
#   ('step', i)            the text and the rail move on to step i
CURSOR_START = (760, 610)
UNIT = 78  # vh of scroll per timeline unit
TIMELINE = [
 ('hold', .5), ('move', 229, 358, .5), ('click', 1), ('step', 1), ('hold', .55),
 ('move', 632, 123, .5), ('click', 2), ('step', 2), ('hold', .65),
 ('move', 40, 188, .55), ('click', 3), ('step', 3), ('hold', .5),
 ('move', 940, 90, .5), ('click', 4), ('hold', .8),
]
LENGTH = sum(t[-1] for t in TIMELINE if t[0] in ('hold', 'move'))

if '--images' in sys.argv:
    from PIL import Image
    d = f'{ROOT}/assets/{FOLDER}/'
    for name, _, layers in SHOTS:
        out = Image.new('RGB', (W * 2, H * 2), 'white')
        for f, x, y in layers:
            im = Image.open(d + f + '.webp').convert('RGBA')
            out.paste(im, (round(x * 2), round(y * 2)), im)
        out.save(d + name + '.webp', quality=84, method=6)

shots = '\n'.join(
    f'              <img class="flow-shot{" is-on" if i == 0 else ""}" src="../assets/{FOLDER}/{f}.webp" alt="{e(alt)}" width="{W * 2}" height="{H * 2}">'
    for i, (f, alt, _) in enumerate(SHOTS))
rail = '\n'.join(
    f'            <li><button type="button" class="flow-dot"{" aria-current=\"step\"" if i == 0 else ""}><b>{i + 1}</b><span>{e(n)}</span></button></li>'
    for i, (n, _) in enumerate(STEPS))
steps = '\n'.join(
    f'            <li class="flow-step{" is-active" if i == 0 else ""}">\n'
    f'              <span class="label">{i + 1:02d} / {len(STEPS):02d}</span>\n              <h3>{e(n)}</h3>\n              <p>{e(t)}</p>\n            </li>'
    for i, (n, t) in enumerate(STEPS))
cx, cy = CURSOR_START
block = f'''    <!-- tour:start (generated by gen_bullseye.py) -->
    <div class="flow" data-flow data-w="{W}" data-h="{H}" data-timeline='{json.dumps(TIMELINE)}' style="--flow-len:{LENGTH * UNIT:.0f}" role="region" aria-label="Screen tour: a farmer’s path through BullsEye">
      <div class="flow-pin">
        <div class="flow-inner">
          <div class="flow-stage">
            <div class="flow-bar">
              <ol class="flow-rail" aria-label="Tour steps">
{rail}
              </ol>
              <a class="flow-skip" href="#details">Skip<i> the tour</i> <span aria-hidden="true">↓</span></a>
            </div>
            <div class="flow-frame">
              <div class="flow-view" style="aspect-ratio:{W} / {H}">
{shots}
                <span class="flow-cursor" aria-hidden="true" style="left:{cx / W * 100:.2f}%;top:{cy / H * 100:.2f}%"><svg viewBox="0 0 24 24"><path d="M5 2.5v17l4.6-4.3 2.9 6.6 2.7-1.2-2.9-6.5h6.2z" fill="#ffd23f" stroke="#141414" stroke-width="1.5" stroke-linejoin="round"/></svg></span>
              </div>
            </div>
          </div>
          <ol class="flow-steps">
{steps}
          </ol>
        </div>
      </div>
    </div>
    <!-- tour:end -->
'''
p = f'{ROOT}/projects/cooling.html'; s = open(p).read()
s, n = re.subn(r' *<!-- tour:start.*?<!-- tour:end -->\n', lambda m: block, s, flags=re.S)
assert n == 1, 'tour markers not found in cooling.html'
open(p, 'w').write(s)
print('ok')
